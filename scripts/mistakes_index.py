"""Write the index table in docs/mistakes/README.md.

    python3 .agents/scripts/mistakes_index.py [--root DIR] [--check]

Agents read this index at the start of a task instead of every mistake note.
Each row holds the date, the title, and the prevention rule in one short line.

The table sits between two marker lines. Text above and below the markers is
kept as it is, so a person can still write a short summary there. When the
markers are missing, the script adds them at the end of the file.

--check changes nothing. It exits 1 when the index is out of date.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

START = "<!-- mistakes-index:start (generated by .agents/scripts/mistakes_index.py) -->"
END = "<!-- mistakes-index:end -->"
RULE_LIMIT = 150

NAME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})_.+\.md$")
TITLE_RE = re.compile(r"^#\s+(.*)$", re.MULTILINE)
DATE_PREFIX_RE = re.compile(r"^\d{4}-\d{2}-\d{2}\s*[—–-]+\s*")
# "## Prevention rule" or "## Rule" (any level, plural too), or "**Prevention rule:**".
HEADING_RE = re.compile(r"^#{2,4}\s*(?:prevention )?rules?\s*$", re.IGNORECASE | re.MULTILINE)
INLINE_RE = re.compile(r"\*\*prevention rules?:?\*\*:?\s*(.+)", re.IGNORECASE)


def _clean(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    text = text.replace("|", "\\|")
    if len(text) > RULE_LIMIT:
        cut = text[:RULE_LIMIT].rsplit(" ", 1)[0]
        text = cut.rstrip(",;:") + " …"
    return text


def prevention_rule(body: str) -> str:
    """Return the first line or bullet of the prevention rule, or ''."""
    heading = HEADING_RE.search(body)
    if heading:
        lines = []
        for line in body[heading.end():].splitlines():
            stripped = line.strip()
            if stripped.startswith("#"):
                break
            if not stripped:
                if lines:
                    break
                continue
            # Keep the first bullet, or the first paragraph.
            if stripped.startswith(("- ", "* ", "1. ")):
                if lines:
                    break
                lines.append(stripped.lstrip("-*1. ").strip())
                continue
            lines.append(stripped)
        return _clean(" ".join(lines))
    inline = INLINE_RE.search(body)
    if inline:
        return _clean(inline.group(1))
    return ""


def title_of(body: str, fallback: str) -> str:
    match = TITLE_RE.search(body)
    title = match.group(1).strip() if match else fallback
    return DATE_PREFIX_RE.sub("", title).replace("|", "\\|")


def build_table(folder: Path) -> str:
    rows = ["| Date | Mistake | Prevention rule |", "| ---- | ------- | --------------- |"]
    for path in sorted(folder.glob("*.md")):
        match = NAME_RE.match(path.name)
        if not match:
            continue
        body = path.read_text(encoding="utf-8")
        rule = prevention_rule(body) or "(no prevention rule written yet)"
        rows.append(f"| {match.group(1)} | [{title_of(body, path.stem)}]({path.name}) | {rule} |")
    return "\n".join(rows)


def render(readme_text: str, table: str) -> str:
    block = f"{START}\n\n{table}\n\n{END}"
    if START in readme_text and END in readme_text:
        before = readme_text.split(START, 1)[0]
        after = readme_text.split(END, 1)[1]
        return f"{before}{block}{after}"
    base = readme_text.rstrip()
    if not base:
        base = "# Mistakes\n\nOne file per incident: `YYYY-MM-DD_topic.md`. Read this index at the start of a task."
    return f"{base}\n\n{block}\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".", help="repository root (default: current folder)")
    parser.add_argument("--check", action="store_true", help="exit 1 when the index is stale")
    args = parser.parse_args(argv)

    folder = Path(args.root) / "docs" / "mistakes"
    if not folder.is_dir():
        print(f"No {folder} folder. Nothing to index.")
        return 0
    readme = folder / "README.md"
    old = readme.read_text(encoding="utf-8") if readme.exists() else ""
    new = render(old, build_table(folder))

    if args.check:
        if new != old:
            print(f"{readme} is out of date. Run: python3 .agents/scripts/mistakes_index.py --root {args.root}")
            return 1
        print(f"{readme} is up to date.")
        return 0
    if new != old:
        readme.write_text(new, encoding="utf-8")
        print(f"Updated {readme}.")
    else:
        print(f"{readme} was already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
